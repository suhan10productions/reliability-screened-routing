"""Build the IJSS: Operations & Logistics manuscript (paper_ijss/routing_model_ijss.tex).

Writes, in paper_ijss/:
  routing_model_ijss.pdf      named version
  ijss_review.pdf             version without identifying information
  ijss_refs.bib, ijss_refs_anon.bib

Run after code/nhsjs_tables.py and code/ijss_tables.py:
  cd code && python3 build_ijss.py
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "paper_ijss"


def write_bibs():
    bib = (ROOT / "paper" / "sn-bibliography.bib").read_text()
    bib = re.sub(r"(edition\s*=\s*)\{2\}", r"\1{2nd}", bib)
    (DIR / "ijss_refs.bib").write_text("% Generated by code/build_ijss.py; do not edit.\n" + bib)
    anon = []
    for entry in re.split(r"(?=^@)", bib, flags=re.M):
        m = re.match(r"@misc\{(ali2026\w*),", entry)
        if m:
            kind = "code and data archive" if m.group(1) == "ali2026archive" else "protocol record"
            entry = (f"@misc{{{m.group(1)},\n  author = {{{{Anonymous}}}},\n  title = {{Public {kind}}},\n"
                     f"  year = {{2026}},\n  note = {{Details removed for review}}\n}}\n\n")
        anon.append(entry)
    (DIR / "ijss_refs_anon.bib").write_text("% Generated by code/build_ijss.py; do not edit.\n" + "".join(anon))


def latex(jobname: str, pre: str = "") -> str:
    arg = f"{pre}\\input{{routing_model_ijss}}"
    for step in ("tex", "bib", "tex", "tex"):
        if step == "tex":
            subprocess.run(["pdflatex", "-interaction=nonstopmode", f"-jobname={jobname}", arg],
                           cwd=DIR, stdout=subprocess.DEVNULL, check=False)
        else:
            subprocess.run(["bibtex", jobname], cwd=DIR, stdout=subprocess.DEVNULL, check=False)
    log = (DIR / f"{jobname}.log").read_text(errors="replace")
    problems = [l for l in log.splitlines() if l.startswith("!") or "undefined" in l.lower() or "Overfull" in l]
    return "\n".join(problems)


def main():
    write_bibs()
    for job, pre in (("routing_model_ijss", ""), ("ijss_review", "\\def\\anonbuild{1}")):
        problems = latex(job, pre)
        print(job, "ok" if not problems else "PROBLEMS:\n" + problems)


if __name__ == "__main__":
    main()
