"""Build the Supporting Information of the ITOR manuscript from the full manuscript.

The SI is the full manuscript (paper/routing_model_orf.tex) without its
introduction, related work, limitations, conclusion and declarations: the model,
every study design, every result section, the reproducibility checks and the
appendices. Sections are numbered S1, S2, ... so the main text can cite them.

  cd code && python3 build_itor_si.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "paper" / "routing_model_orf.tex"
OUT = ROOT / "paper_itor" / "supporting_information.tex"


def between(text: str, start: str, end: str) -> str:
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


def main():
    s = SRC.read_text()
    body = between(s, r"\section{Problem definition}", r"\section{Limitations}")
    appx = between(s, r"\section{Origin of the weight vector}", r"\begingroup")
    body = body.replace(r"\section{Problem definition}", r"\section{Problem definition}\label{sec:si-model}", 1)
    body = body.replace(r"\section{Results}", r"\section{Results of every study}\label{sec:si-dev}", 1)
    # the main text holds the limitations; the SI only points there
    tail = ("Reproducibility shows that the reported numbers follow from the archived code and\n"
            "records. It does not show that the synthetic instances or the assumed disturbance\n"
            "model represent a real operation; that needs the evidence listed in\n"
            "Section~\\ref{sec:limitations}.\n")
    assert tail in body
    body = body.replace(tail, "Reproducibility shows that the reported numbers follow from the archived code and\n"
                              "records. It does not show that the synthetic instances or the assumed disturbance\n"
                              "model represent a real operation.\n")
    for old, new in [("Section~\\ref{sec:limitations}", "the main text"),
                     ("Appendix~\\ref{", "Section~\\ref{"), ("the appendix", "Section~\\ref{sec:additional}")]:
        body = body.replace(old, new)
        appx = appx.replace(old, new)
    assert "sec:limitations" not in body + appx
    # commit hashes: let them break across lines
    import re
    body = re.sub(r"\\texttt\{([0-9a-f]{40})\}", lambda m: "\\texttt{" + "\\allowbreak ".join(m.group(1)[k:k + 8] for k in range(0, 40, 8)) + "}", body)

    preamble = r"""%% Supporting Information for the ITOR manuscript. Generated by code/build_itor_si.py
%% from paper/routing_model_orf.tex; do not edit by hand.
\documentclass[11pt,letterpaper]{article}
\usepackage[margin=1in]{geometry}
\usepackage{mathptmx}
\usepackage{setspace}
\setstretch{1.1}
\usepackage{amsmath,amssymb,booktabs,array,graphicx,microtype,float}
\usepackage{xcolor}
\usepackage{caption}
\captionsetup{labelfont=bf,labelsep=period,font=small}
\usepackage[authoryear,round]{natbib}
\let\cite\citep
\usepackage{hyperref}
\hypersetup{colorlinks=true,linkcolor={blue!55!black},citecolor={blue!55!black},urlcolor={blue!55!black}}
\providecommand{\bibcommenthead}{}
\setlength{\emergencystretch}{3em}
\usepackage{tocloft}
\setlength{\cftsecnumwidth}{2.4em}
\setlength{\cftsubsecnumwidth}{3.6em}
\makeatletter
\def\input@path{{../paper/}}
\makeatother
\graphicspath{{../paper/}}
\renewcommand{\thesection}{S\arabic{section}}
\renewcommand{\thetable}{S\arabic{table}}
\renewcommand{\thefigure}{S\arabic{figure}}
\renewcommand{\theequation}{S\arabic{equation}}
\input{result_macros_v7.tex}
\input{result_macros_v8.tex}
\input{result_macros_v9.tex}
\input{result_macros_v10.tex}
\input{result_macros_v11.tex}
\input{result_macros_v12.tex}
\title{Supporting Information for ``Reliability screening for vehicle routing with
time windows: a solver-independent alternative to travel-time padding''}
\author{Suhan Ali}
\date{}
\begin{document}
\maketitle
\noindent This document gives the full model, the design of every study, every result table and the
further exploratory checks. All numbers are generated from the records in the archive
\citep{ali2026archive}.
\tableofcontents
\clearpage
"""
    end = "\n\\clearpage\n\\bibliographystyle{apalike}\n\\bibliography{../paper/sn-bibliography}\n\\end{document}\n"
    OUT.write_text(preamble + body + "\n\\clearpage\n" + appx + end)
    print("SI written:", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
